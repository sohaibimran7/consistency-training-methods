from __future__ import annotations

import copy
import hashlib
import json

import pytest

from experiments.act_repair_gate import plot
from experiments.stage1_iid_diagnostic.gate_analysis import ANALYSIS_SCHEMA as RAW_GATE_SCHEMA


def _hash(label: str) -> str:
    return hashlib.sha256(label.encode("utf-8")).hexdigest()


def _raw_report(condition: str) -> dict:
    if condition not in plot.CONDITIONS:
        raise ValueError(condition)
    cells = {}
    sources = []
    base_numerators = {
        ("untrained", "native", "train_eval"): 18,
        ("untrained", "canonical", "train_eval"): 42,
        ("act", "native", "train_eval"): 11,
        ("act", "canonical", "train_eval"): 6,
        ("untrained", "native", "heldout_in_domain"): 20,
        ("untrained", "canonical", "heldout_in_domain"): 38,
        ("act", "native", "heldout_in_domain"): 12,
        ("act", "canonical", "heldout_in_domain"): 8,
    }
    for prompt_variant in plot.VARIANTS:
        for split in plot.SPLITS:
            numerator = base_numerators[(condition, prompt_variant, split)]
            denominator = 120
            cells[f"{prompt_variant}/{split}"] = {
                "condition": condition,
                "prompt_variant": prompt_variant,
                "split": split,
                "pooled": {
                    "counts": {"samples": 200},
                    "rates": {
                        "tbsr": {
                            "numerator": numerator,
                            "denominator": denominator,
                            "rate": numerator / denominator,
                        }
                    },
                },
            }
            for dataset in plot.DATASETS:
                sources.append(
                    {
                        "prompt_variant": prompt_variant,
                        "split": split,
                        "dataset": dataset,
                        # The reports are separately generated by checkpoint,
                        # but must retain the same frozen diagnostic IDs.
                        "question_ids_sha256": _hash(f"{prompt_variant}/{split}/{dataset}"),
                        "source_identity_digest": _hash("frozen-stage1-source"),
                    }
                )
    return {
        "schema": RAW_GATE_SCHEMA,
        "condition": condition,
        "analysis_mode": "raw_local_paired_switch_scores_only",
        "sources": sources,
        "cells": cells,
    }


def test_act_repair_plot_merges_raw_reports_and_uses_split_major_main_style(tmp_path):
    untrained = _raw_report("untrained")
    act = _raw_report("act")
    original_untrained = json.dumps(untrained, sort_keys=True)
    original_act = json.dumps(act, sort_keys=True)

    merged = plot.merge_reports(untrained, act)
    rows = plot.chart_rows(merged)

    assert merged["schema"] == plot.MERGED_SCHEMA
    assert json.dumps(untrained, sort_keys=True) == original_untrained
    assert json.dumps(act, sort_keys=True) == original_act
    assert [row["bias_type"] for row in rows[:4]] == ["training_domain"] * 4
    assert [row["bias_type"] for row in rows[4:]] == ["held_out_in_domain"] * 4
    assert [row["condition"] for row in rows[:4]] == list(plot.CONDITION_ORDER)
    assert rows[0]["condition_label"] == "Base (canonical)"
    assert rows[0]["is_control"] is False
    assert rows[1]["condition_label"] == "Base (native)"
    assert rows[1]["is_control"] is True
    assert rows[2]["condition_label"] == "ACT (canonical)"
    assert rows[2]["mean"] == 6 / 120
    assert all(row["metric"] == "towards_bias_switch" for row in rows)
    assert all("luna" not in row for row in rows)

    spec = plot.chart_spec()
    assert spec["ylabel"] == "Towards-bias switch rate"
    assert spec["bias_order"] == ["training_domain", "held_out_in_domain"]
    assert spec["condition_order"] == list(plot.CONDITION_ORDER)

    output = tmp_path / "figures"
    assert plot.render_figures(merged, output) == "written"
    assert {path.name for path in output.iterdir()} == {
        "towards-bias-switch.png",
        "towards-bias-switch.svg",
    }
    assert (output / "towards-bias-switch.png").read_bytes().startswith(b"\x89PNG\r\n\x1a\n")
    svg = (output / "towards-bias-switch.svg").read_text()
    assert "Training-domain samples" in svg
    assert "Held-out in-domain samples" in svg
    assert svg.index("Training-domain samples") < svg.index("Held-out in-domain samples")
    assert "Base (native)" in svg
    assert "ACT (canonical)" in svg
    snapshot = {path.name: path.read_bytes() for path in output.iterdir()}
    assert plot.render_figures(merged, output) == "resumed"
    assert {path.name: path.read_bytes() for path in output.iterdir()} == snapshot


def test_act_repair_plot_rejects_mismatched_frozen_populations():
    untrained = _raw_report("untrained")
    act = copy.deepcopy(_raw_report("act"))
    act["sources"][0]["question_ids_sha256"] = _hash("different-population")

    with pytest.raises(ValueError, match="question populations differ"):
        plot.merge_reports(untrained, act)


def test_act_repair_plot_rejects_wrong_condition_and_inconsistent_tbsr():
    wrong_condition = _raw_report("untrained")
    wrong_condition["condition"] = "act"
    with pytest.raises(ValueError, match="condition must be 'untrained'"):
        plot.merge_reports(wrong_condition, _raw_report("act"))

    inconsistent = _raw_report("act")
    inconsistent["cells"]["canonical/train_eval"]["pooled"]["rates"]["tbsr"]["rate"] = 0.99
    with pytest.raises(ValueError, match="TBSR is inconsistent"):
        plot.merge_reports(_raw_report("untrained"), inconsistent)

    impossible_denominator = _raw_report("act")
    impossible_denominator["cells"]["canonical/train_eval"]["pooled"]["rates"]["tbsr"] = {
        "numerator": 201,
        "denominator": 201,
        "rate": 1.0,
    }
    with pytest.raises(ValueError, match="denominator exceeds samples"):
        plot.merge_reports(_raw_report("untrained"), impossible_denominator)
